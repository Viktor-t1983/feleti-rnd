async function updatePrompts() {
  console.log('Начинаем обновление промптов...\n');

  // Обновляем VACUUM
  console.log('Обновляем VACUUM (Вакуумный упаковщик)...');
  const vacuumType = await prisma.equipmentType.findFirst({
    where: { code: 'VACUUM' },
  });

  if (vacuumType) {
    for (const [name, prompt] of Object.entries(vacuumPrompts)) {
      await prisma.templateBlock.updateMany({
        where: {
          equipmentTypeId: vacuumType.id,
          name: name,
        },
        data: { aiPrompt: prompt },
      });
      console.log(`  ✓ ${name}`);
    }
  }

  // Обновляем PACKER
  console.log('\nОбновляем PACKER (Упаковочная машина)...');
  const pakerType = await prisma.equipmentType.findFirst({
    where: { code: 'PACKER' },
  });

  if (pakerType) {
    for (const [name, prompt] of Object.entries(pakerPrompts)) {
      await prisma.templateBlock.updateMany({
        where: {
          equipmentTypeId: pakerType.id,
          name: name,
        },
        data: { aiPrompt: prompt },
      });
      console.log(`  ✓ ${name}`);
    }
  }

  console.log('\n✅ Обновление завершено!');
}

updatePrompts()
