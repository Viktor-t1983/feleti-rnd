const fastifyJwt = require('@fastify/jwt');
const Fastify = require('fastify');
const jwt = require('jsonwebtoken');

async function testJWTCompatibility() {
  console.warn('=== Testing JWT Compatibility ===\n');

  const secret = 'your-super-secret-jwt-key-change-in-production';
  const payload = {
    userId: 'test-user-id-123',
    email: 'test@example.com',
    role: 'engineer'
  };

  // 1. Generate token with jsonwebtoken (same as token.ts)
  const token = jwt.sign(payload, secret, {
    expiresIn: '7d',
    issuer: 'feleti-api',
    audience: 'feleti-users'
  });

  console.warn('1. Token generated with jsonwebtoken:');
  console.warn(`   Token (first 50 chars): ${token.substring(0, 50)}...`);
  console.warn(`   Full token: ${token}\n`);

  // 2. Verify with jsonwebtoken (same as token.ts verifyAccessToken)
  try {
    const decoded = jwt.verify(token, secret, {
      issuer: 'feleti-api',
      audience: 'feleti-users'
    });
    console.warn('2. Verification with jsonwebtoken: SUCCESS');
    console.warn(`   Decoded payload:`, decoded);
  } catch (error) {
    console.error('2. Verification with jsonwebtoken: FAILED');
    console.error(`   Error: ${error.message}`);
  }

  console.warn('\n3. Testing with @fastify/jwt...');

  // 3. Create Fastify instance and register jwt plugin
  const fastify = Fastify({ logger: false });

  try {
    await fastify.register(fastifyJwt, {
      secret,
      sign: {
        expiresIn: '7d',
        issuer: 'feleti-api',
        audience: 'feleti-users'
      },
      verify: {
        issuer: 'feleti-api',
        audience: 'feleti-users'
      }
    });

    // Try to verify the token generated by jsonwebtoken
    await fastify.ready();

    try {
      const verified = fastify.jwt.verify(token);
      console.warn('   Verification with @fastify/jwt: SUCCESS');
      console.warn(`   Verified payload:`, verified);
    } catch (error) {
      console.error('   Verification with @fastify/jwt: FAILED');
      console.error(`   Error: ${error.message}`);
      console.error(`   Error code: ${error.code}`);
    }

  } catch (error) {
    console.error('   Failed to setup Fastify JWT:', error.message);
  }

  console.warn('\n=== Test Complete ===');
}

testJWTCompatibility().catch(console.error);
